/**
 * Email send helper — single entry point for every outgoing message.
 *
 * Wraps the Resend SDK with:
 *   - Graceful no-op when RESEND_API_KEY isn't configured (instead of
 *     throwing, returns { ok: false, reason: "not_configured" }). Lets
 *     the rest of the system keep working when email is offline.
 *   - Consistent return shape so callers can branch on success without
 *     dealing with thrown errors / network exceptions.
 *   - Category tagging via Resend's tags feature for later analytics
 *     ("how many renewal reminders did we send last week?").
 *
 * Every caller — renewal cron, commission notification, invite — goes
 * through this single helper so any future cross-cutting concern
 * (rate limiting, suppression list checks, unsubscribe handling)
 * lives in exactly one place.
 */

import { getEmailFrom, getResendClient } from "./client";

export interface SendEmailOptions {
  /** Single recipient or array — Resend accepts both. */
  to: string | string[];
  subject: string;
  /** HTML body. Plain-text version is auto-generated by Resend. */
  html: string;
  /** Optional category tag for analytics ("renewal_reminder", "invite", etc.). */
  category?: string;
  /** Optional Reply-To address — defaults to no reply-to header. */
  replyTo?: string;
  /**
   * Personalized sender display name. When set, the From header becomes
   * `"{fromName} via Credibly" <configured-address>` — the DocuSign /
   * Calendly pattern. The ADDRESS part always stays on our verified
   * domain (deliverability: SPF/DKIM only authorize our domain), only
   * the display name changes. Pair with `replyTo` so responses land in
   * the sender's real inbox. Unset = the platform default sender.
   */
  fromName?: string;
  /**
   * Custom sender display name used EXACTLY as given — no "via Credibly"
   * suffix (the GHL-style per-automation sender). Takes precedence over
   * `fromName` when both are set.
   */
  fromNameExact?: string;
  /**
   * Custom mailbox (local part, before the @) for the From address. The
   * domain always stays the configured verified domain — a mailbox on a
   * verified domain delivers without extra setup, any other domain
   * would be rejected by Resend. Invalid characters are stripped; an
   * empty result falls back to the configured address.
   */
  fromLocal?: string;
}

/**
 * Strip every character with meaning inside an email header (angle
 * brackets, quotes, newlines, separators) from a user-controlled
 * display name to rule out header injection, and cap the length so
 * inbox UIs don't truncate awkwardly.
 */
function cleanDisplayName(name: string): string {
  return name
    .replace(/[<>"\\\r\n;,@]/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, 48)
    .trim();
}

/**
 * Build the From header. The ADDRESS domain always stays the configured
 * verified domain (deliverability: SPF/DKIM only authorize our domain);
 * `fromLocal` may swap the mailbox in front of it, and the display name
 * comes from `fromNameExact` (used as typed) or `fromName` (suffixed
 * "via Credibly"). All three are user-controlled text, so names are
 * header-sanitized and the mailbox is reduced to safe address chars.
 */
function buildFrom(opts: {
  fromName?: string;
  fromNameExact?: string;
  fromLocal?: string;
}): string {
  const configured = getEmailFrom();
  /* Pull the bare address out of `Name <addr>` (or use as-is when the
     env var holds a bare address). */
  const match = configured.match(/<([^>]+)>/);
  let address = match ? match[1] : configured;

  if (opts.fromLocal) {
    const local = opts.fromLocal
      .toLowerCase()
      .replace(/[^a-z0-9._-]/g, "")
      .replace(/^[._-]+|[._-]+$/g, "")
      .slice(0, 48);
    const at = address.lastIndexOf("@");
    if (local && at > -1) address = `${local}${address.slice(at)}`;
  }

  const exact = opts.fromNameExact ? cleanDisplayName(opts.fromNameExact) : "";
  if (exact) return `${exact} <${address}>`;

  const name = opts.fromName ? cleanDisplayName(opts.fromName) : "";
  if (name) return `${name} via Credibly <${address}>`;

  /* No display-name override: keep the configured name but honour a
     mailbox override (configured may be `Name <addr>` or bare). */
  if (opts.fromLocal && match) {
    return `${configured.slice(0, configured.indexOf("<"))}<${address}>`.trim();
  }
  return opts.fromLocal ? address : configured;
}

export type SendEmailResult =
  | { ok: true; id: string }
  | { ok: false; reason: "not_configured" | "send_failed"; error?: string };

/**
 * Send an email via Resend. Never throws — returns a discriminated
 * union the caller can pattern-match on.
 */
export async function sendEmail(
  opts: SendEmailOptions,
): Promise<SendEmailResult> {
  const client = getResendClient();
  if (!client) {
    return { ok: false, reason: "not_configured" };
  }
  try {
    const { data, error } = await client.emails.send({
      from: buildFrom(opts),
      to: opts.to,
      subject: opts.subject,
      html: opts.html,
      replyTo: opts.replyTo,
      tags: opts.category
        ? [{ name: "category", value: opts.category }]
        : undefined,
    });
    if (error || !data?.id) {
      return {
        ok: false,
        reason: "send_failed",
        error: error?.message || "Unknown Resend error",
      };
    }
    return { ok: true, id: data.id };
  } catch (err) {
    return {
      ok: false,
      reason: "send_failed",
      error: err instanceof Error ? err.message : String(err),
    };
  }
}
